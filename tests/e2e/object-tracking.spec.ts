import { test,expect } from "./fixture";
import { typeMessage } from "./ui-helpers";
test.use({reducedMotion:"reduce",viewport:{width:390,height:844}});
test("unsupported MP4 is explained in conversation without dispatching SAM",async({page,context})=>{
  await context.grantPermissions(["camera"]);
  await page.addInitScript(()=>{MediaRecorder.isTypeSupported=()=>false;});
  let view:Record<string,unknown>,calls=0;
  await page.routeWebSocket("**/events",()=>{});
  await page.route("**/api/session",async route=>{view=await(await route.fetch()).json();view.key={connected:true,models:["muse-spark-test"]};await route.fulfill({json:view});});
  await page.route("**/api/phase",route=>route.fulfill({json:view}));
  await page.route("**/api/track",route=>{calls++;return route.fulfill({status:500});});
  await page.goto("/");await typeMessage(page,"Track my mouse");
  await page.getByRole("button",{name:"Send message",exact:true}).click();
  const card=page.getByRole("region",{name:"Movement check"});
  await card.getByRole("button",{name:"Open camera",exact:true}).click();
  await card.getByRole("button",{name:"Ready — check movement"}).click();
  await expect(card.getByRole("alert")).toContainText("MP4");expect(calls).toBe(0);
  await card.getByRole("button",{name:"Not now"}).click();
  await expect(card).toHaveCount(0);
});
